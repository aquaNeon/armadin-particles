  // ---------------------------------------------------------------- text field
  //
  // Copy in the middle of the field behaves like an obstacle. Each phrase is
  // rasterised once, turned into a signed distance field, and every particle
  // closer than (pad + its own radius) is pushed out along the field gradient.
  // Accounting for the particle's own radius is what makes the edge read as a
  // packing boundary rather than a stencil: a 1.8cm disc keeps its centre
  // further out than a 0.3cm one, so the small discs fill the tight corners of
  // the letterforms exactly like they do against a neighbour.
  //
  // The push is scaled by the phrase's own opacity. A phrase that is fading
  // out therefore stops holding its hole at precisely the rate it stops being
  // visible, and the pack flows back into the vacated space under the forces
  // that are already there. Two phrases are live at once during a crossfade,
  // so a smaller phrase establishes its hole while the larger one releases --
  // which is the whole point of the effect.
  //
  // v2: the keep-out shape is a BLOAT of the glyphs, not the glyphs. Every
  // glyph cell is dilated by text-bloat-em (a fraction of the phrase's own
  // font size, so it scales with the type), which does three jobs at once:
  // it merges the letters of a word into one mass, swallows every counter and
  // kerning gap, and grows the outer contour into the soft rounded blob the
  // comp shows. v1 sealed with a CLOSING (dilate then erode), which filled
  // gaps but put the outline straight back on the letterforms -- so discs
  // still hugged each stroke and small ones nested in wide counters and word
  // spaces. Dilation keeps the growth.
  //
  // text-pad then adds the per-disc packing clearance on top of the bloat,
  // and text-halo adds a weak, smoothly decaying push OUTSIDE that band so
  // the density thins toward the copy instead of piling into a hard rim.
  // data-text="0" disables the whole thing.
  //
  // The SDF lives in screen pixels, not cm. The cm frame is stretched to fill
  // the viewport (see gl_Position), so baking type in cm would shear it at any
  // window aspect other than the render aspect. Distances convert back to cm
  // with the same geometric-mean scale the shader uses for disc size, and grid
  // gradients are un-stretched per axis before they become a cm direction.

  var TXT = {
    bloatEm:  num(d.textBloatEm, 0.30),   // keep-out growth, as a share of font size
    bloatMin: num(d.textBloatMin, 1.6),   // cm floor, so small type still merges
    bloat:    num(d.textBloat, -1),       // cm; >= 0 overrides both of the above
    pad:      num(d.textPad, 1.1),        // cm of packing clearance on top of the bloat
    radFloor: num(d.textRadFloor, 0.6),   // cm; smallest disc keeps at least this gap
    jitter:   num(d.textJitter, 1.8),     // cm; +/- spread of the clearance band
    strength: num(d.textStrength, 520),
    wall:     num(d.textWall, 2.2),       // cubic stiffening term at the boundary
    halo:     num(d.textHalo, 7),         // cm of soft thinning outside the band
    haloK:    num(d.textHaloPush, 0.15),  // halo push, as a share of strength
    pull:     num(d.textPull, 0.65),      // release draw, as a share of push
    reach:    num(d.textReach, 9),       // cm the release draw extends past the band
    proj:     num(d.textProj, 1),         // positional correction, 0..1
    settle:   Math.max(0, num(d.textSettle, 0) | 0),  // extra separate+project trips
    hold:     num(d.textHold, 4.5),       // s a phrase sits still
    fade:     num(d.textFade, 2.2),       // s of crossfade
    tracking: num(d.textTracking, -0.015),// em
    lineH:    num(d.textLine, 1.06),
    maxW:     num(d.textMaxW, 0.86),      // longest line, as a fraction of the viewport
    weight:   d.textWeight || "600",
    family:   d.textFamily || 'Geist, "Helvetica Neue", "Segoe UI", system-ui, sans-serif',
    color:    d.textColor || CFG.ink,
    raster:   0.5,                        // SDF grid is half the display res
    on:       d.text !== "0",
    items:    [],
    ready:    false,
    sx: 1, sy: 1, sg: 1, W: 0, H: 0,
  };

  // Dilating by B merges anything separated by less than 2B, so B has to beat
  // half the widest internal gap in the type. At weight 600 a counter runs
  // about 0.28em and a word space about 0.25em, so 0.30em clears both with
  // room to spare -- and the same number is the margin the copy ends up
  // sitting in, because dilation grows the outer contour too. The cm floor is
  // there for small type, where 0.30em would be under one disc diameter.
  function bloatCmFor(item) {
    if (TXT.bloat >= 0) return TXT.bloat;
    var em = item.sizeCm * (item.fit || 1);
    var v = TXT.bloatEm * em;
    var floor = Math.max(TXT.bloatMin, TXT.pad + SCENE.minR);
    return v > floor ? v : floor;
  }

